export type TKey = keyof Dict;

const dicts = { en, bn };

export function translate(lang: 'en' | 'bn', key: TKey, vars?: Record<string, string | number>) {
  let s = (dicts[lang] || en)[key] || en[key] || key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function useT() {
  const lang = useConfig((s) => s.config.features.language);
  return (key: TKey, vars?: Record<string, string | number>) => translate(lang, key, vars);
}
